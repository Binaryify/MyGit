package main

import (
	"os"
	"os/exec"
	"path/filepath"
	"testing"
)

// commitFiles commits files, by name and text, in the tester's repository.
func (tt *tester) commitFiles(t *testing.T, msg string, files map[string]string) {
	t.Helper()
	dir := tt.a.repo.Dir
	for name, text := range files {
		p := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	for _, args := range [][]string{{"add", "."}, {"commit", "-q", "-m", msg}} {
		cmd := exec.Command("git", args...)
		cmd.Dir = dir
		cmd.Env = append(os.Environ(), "GIT_AUTHOR_NAME=Ada", "GIT_AUTHOR_EMAIL=a@example.com",
			"GIT_COMMITTER_NAME=Ada", "GIT_COMMITTER_EMAIL=a@example.com")
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
	}
	tt.a.refresh()
	tt.settle()
}

func TestGeneratedFilesFold(t *testing.T) {
	tt := newTester(t)
	tt.commitFiles(t, "Bump the deps", map[string]string{
		"go.sum":         "example.com/a v1.0.0 h1:abc=\n",
		"api_gen.go":     "// Code generated by gen. DO NOT EDIT.\n\npackage main\n",
		"assets/app.css": "body {}\n",
		".gitattributes": "assets/*.css linguist-generated\n",
		"main.go":        "package main\n\nfunc main() { run() }\n",
		"docs/notes.md":  "# Notes\n",
	})
	tt.click(t, "Bump the deps")
	d := &tt.a.detail
	gen := map[string]bool{}
	for i, f := range d.files {
		gen[fileName(f)] = d.generated[i]
	}
	for name, want := range map[string]bool{"go.sum": true, "api_gen.go": true, "assets/app.css": true,
		".gitattributes": false, "main.go": false, "docs/notes.md": false} {
		if gen[name] != want {
			t.Errorf("%s generated %v, want %v (%v)", name, gen[name], want, gen)
		}
	}
	// The first file shown is one people wrote.
	if d.folded || d.generated[d.fileSel] || d.diff == nil {
		t.Fatalf("first file %q folded %v", fileName(d.files[d.fileSel]), d.folded)
	}
	for i, f := range d.files {
		if fileName(f) == "go.sum" {
			tt.a.showFile(i)
		}
	}
	tt.Frame()
	if !d.folded || d.diff != nil || !tt.HasText("生成的文件，已折叠") {
		t.Fatalf("go.sum not folded: %q", tt.Texts())
	}
	tt.click(t, "显示 diff")
	if d.folded || d.diff == nil {
		t.Fatal("go.sum still folded once asked for")
	}
}

func TestViewedFiles(t *testing.T) {
	tt := newTester(t)
	tt.commitFiles(t, "Three files", map[string]string{"a.go": "package a\n", "b.go": "package b\n", "c.go": "package c\n"})
	tt.click(t, "Three files")
	a := tt.a
	if !tt.HasText("已看 0/4") {
		t.Fatalf("no count: %q", tt.Texts())
	}
	// Marking the file shown viewed goes on to the next.
	a.toggleViewed(a.detail.fileSel)
	tt.Frame()
	if !a.isViewed(0) || a.detail.fileSel != 1 || !tt.HasText("已看 1/4") {
		t.Fatalf("viewed %v, chosen %d: %q", a.isViewed(0), a.detail.fileSel, tt.Texts())
	}
	a.toggleViewed(0)
	if a.isViewed(0) || a.viewedCount() != 0 {
		t.Error("unmarking left it viewed")
	}
	// Another commit's files are viewed apart.
	a.toggleViewed(2)
	tt.click(t, "Merge the feature")
	if a.viewedCount() != 0 {
		t.Error("a file viewed in one commit shows viewed in another")
	}
}

func TestGeneratedChangeFolds(t *testing.T) {
	tt := newTester(t)
	if err := os.WriteFile(filepath.Join(tt.a.repo.Dir, "yarn.lock"), []byte("# yarn lockfile v1\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	tt.a.refresh()
	tt.settle()
	ch, ok := find(tt.a.unstaged, "yarn.lock")
	if !ok {
		t.Fatalf("no yarn.lock among %v", tt.a.unstaged)
	}
	tt.a.showChange(ch, false)
	tt.settle()
	if d := tt.a.detail; !d.folded || d.diff != nil {
		t.Fatalf("yarn.lock not folded: %+v", d)
	}
	tt.click(t, "显示 diff")
	if d := tt.a.detail; d.folded || d.diff == nil {
		t.Fatal("yarn.lock still folded once asked for")
	}
}
