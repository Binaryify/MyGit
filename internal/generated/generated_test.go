package generated

import "testing"

func TestName(t *testing.T) {
	for p, want := range map[string]bool{
		"package-lock.json":           true,
		"web/pnpm-lock.yaml":          true,
		"go.sum":                      true,
		"dist/app.min.js":             true,
		"api/user.pb.go":              true,
		"vendor/github.com/x/y.go":    true,
		"web/node_modules/a/index.js": true,
		"main.go":                     false,
		"src/lock.go":                 false,
		"docs/vendors.md":             false,
		"min.js":                      false,
	} {
		if got := Name(p); got != want {
			t.Errorf("Name(%q) = %v, want %v", p, got, want)
		}
	}
}

func TestHeader(t *testing.T) {
	if !Header([]string{"// Code generated by mygo generate. DO NOT EDIT.", "", "package locales"}) {
		t.Error("Go's header not seen")
	}
	if !Header([]string{"/**", " * @generated SignedSource<<abc>>", " */"}) {
		t.Error("@generated not seen")
	}
	if Header([]string{"package main", "", "// Code generated below is checked by hand."}) {
		t.Error("a comment without DO NOT EDIT seen as a header")
	}
	if Header([]string{"a", "b", "c", "d", "e", "// Code generated by x. DO NOT EDIT."}) {
		t.Error("a line past the first five seen")
	}
}
