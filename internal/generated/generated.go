// Package generated tells files people don't write from those they do:
// lockfiles, minified and compiled files, dependencies checked in, and
// files saying they are generated, so a diff can fold them away.
package generated

import (
	"path"
	"strings"
)

// lockfiles are the files package managers write, by name.
var lockfiles = map[string]bool{
	"package-lock.json": true, "npm-shrinkwrap.json": true, "yarn.lock": true,
	"pnpm-lock.yaml": true, "bun.lock": true, "bun.lockb": true, "deno.lock": true,
	"go.sum": true, "go.work.sum": true, "Cargo.lock": true, "Gemfile.lock": true,
	"composer.lock": true, "poetry.lock": true, "Pipfile.lock": true, "uv.lock": true,
	"pdm.lock": true, "flake.lock": true, "Podfile.lock": true, "Package.resolved": true,
	"pubspec.lock": true, "mix.lock": true, "packages.lock.json": true, "gradle.lockfile": true,
}

// suffixes are the endings of minified, mapped and compiled files.
var suffixes = []string{
	".min.js", ".min.mjs", ".min.css", ".js.map", ".css.map",
	".pb.go", "_pb2.py", "_pb2.pyi", ".pb.swift", ".g.dart", ".freezed.dart",
	".designer.cs", ".snap",
}

// folders hold dependencies checked in.
var folders = []string{"node_modules", "vendor", "bower_components", ".yarn", "Pods", "third_party"}

// Name tells whether path names a generated file by its name or folder.
func Name(p string) bool {
	base := path.Base(p)
	if lockfiles[base] {
		return true
	}
	for _, s := range suffixes {
		if strings.HasSuffix(base, s) {
			return true
		}
	}
	for _, dir := range strings.Split(path.Dir(p), "/") {
		for _, f := range folders {
			if dir == f {
				return true
			}
		}
	}
	return false
}

// Header tells whether a file's first lines say it is generated, as Go's
// "Code generated … DO NOT EDIT." and the @generated of other tools do.
func Header(lines []string) bool {
	for i, l := range lines {
		if i == 5 {
			break
		}
		if strings.Contains(l, "@generated") ||
			strings.Contains(l, "Code generated") && strings.Contains(l, "DO NOT EDIT") ||
			strings.Contains(l, "<auto-generated") {
			return true
		}
	}
	return false
}
